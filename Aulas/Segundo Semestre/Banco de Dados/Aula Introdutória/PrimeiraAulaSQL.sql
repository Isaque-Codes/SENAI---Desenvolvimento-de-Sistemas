-- LISTAR DADOS INSERIDOS
SELECT * FROM Funcionario;

-- LISTAR IDS E NOMES DOS FUNCIONARIOS
SELECT Codigo, Nome FROM Funcionario;

-- LISTAR FUNCIONARIOS COM ID >2
SELECT * FROM Funcionario WHERE Codigo > 2;

-- LISTAR FUNCIONARIOS QUE COMECEM COM A LETRA I
SELECT * FROM Funcionario WHERE Nome LIKE 'I%';

-- LISTAR FUNCIONARIOS QUE TERMINEM COM A LETRA O
SELECT * FROM Funcionario WHERE Nome LIKE '%o';

-- ORDENAR VALORES
-- EM ORDEM DECRESCENTE
SELECT * FROM Funcionario
ORDER BY Codigo DESC;

-- EM ORDEM ALFABETICA
SELECT * FROM Funcionario
ORDER BY Nome ASC;

