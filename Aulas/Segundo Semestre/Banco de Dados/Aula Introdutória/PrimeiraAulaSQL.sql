DROP DATABASE Empresa; -- APAGAR BASE DE DADOS
CREATE DATABASE Empresa; -- CRIAR BASE DE DADOS

USE Empresa; -- ACESSAR BASE DE DADOS

-- CRIAR TABELA FUNCIONARIO
CREATE TABLE Funcionario(
	Codigo INT PRIMARY KEY,
	Nome NVARCHAR(100), -- O VARCHAR SEM N NAO PERMITE CARACTERES ESPECIAIS
	);

-- INSERIR VALORES EM TABELAS
